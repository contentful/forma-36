import React from 'react';
import { cx } from '@emotion/css';
import { XIcon } from '@contentful/f36-icons';
import {
  Flex,
  type PropsWithHTMLElement,
  type CommonProps,
} from '@contentful/f36-core';
import { IconButton } from '@contentful/f36-button';
import { Text, Subheading } from '@contentful/f36-typography';

import { useModalHeader } from '../useModalHeader';
import { getModalDisplayHeaderStyles } from './ModalDisplayHeader.styles';

interface ModalDisplayHeaderInternalProps extends CommonProps {
  /** */
  illustration?: React.ReactNode;
  /** Title of the modal, used also as reference for accessible labeling */
  title: string;
  /**Subtitle of the modal, used also as reference for accessible labeling */
  subtitle?: string;
  /**Used for linking aria-labelledby, fallback is autogenerated */
  titleId?: string;
  /**Used for linking aria-describedby, fallback is autogenerated */
  subtitleId?: string;
  aria?: {
    closeIconLabel?: string;
  };
}

export type ModalDisplayHeaderProps = PropsWithHTMLElement<
  ModalDisplayHeaderInternalProps,
  'div'
>;

export const ModalDisplayHeader = ({
  title,
  titleId,
  subtitleId,
  subtitle,
  testId = 'cf-ui-modal-header',
  className,
  illustration,
  aria,
  ...otherProps
}: ModalDisplayHeaderProps): React.ReactElement => {
  const styles = getModalDisplayHeaderStyles();
  const {
    titleId: resolvedTitleId,
    subtitleId: resolvedSubtitleId,
    onClose: resolvedOnClose,
    closeIconLabel,
  } = useModalHeader({
    title,
    subtitle,
    titleId,
    subtitleId,
    closeIconLabel: aria?.closeIconLabel,
  });

  return (
    <Flex
      {...otherProps}
      className={cx(styles.root, className)}
      testId={testId}
      alignItems="top"
    >
      <Flex flexDirection="column" alignItems="center" flexGrow={1}>
        {illustration && (
          <div className={styles.illustration}>{illustration}</div>
        )}
        <Text as="hgroup" isTruncated>
          <Subheading
            id={resolvedTitleId}
            as="h2"
            marginBottom="none"
            className={styles.title}
          >
            {title}
          </Subheading>
          {subtitle && (
            <Text
              id={resolvedSubtitleId}
              marginLeft="spacingXs"
              fontColor="gray700"
              as="p"
              className={styles.title}
            >
              {subtitle}
            </Text>
          )}
        </Text>
      </Flex>
      {resolvedOnClose && (
        <Flex
          alignItems="top"
          className={styles.buttonContainer}
          alignSelf="top"
        >
          <IconButton
            variant="transparent"
            aria-label={closeIconLabel}
            size="small"
            icon={<XIcon size="small" />}
            onClick={resolvedOnClose}
          />
        </Flex>
      )}
    </Flex>
  );
};

ModalDisplayHeader.displayName = 'ModalDisplayHeader';
