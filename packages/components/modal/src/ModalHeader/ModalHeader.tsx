import React from 'react';
import ReactModal from 'react-modal';
import { cx } from '@emotion/css';
import { XIcon } from '@contentful/f36-icons';
import {
  Flex,
  type PropsWithHTMLElement,
  type CommonProps,
} from '@contentful/f36-core';
import { IconButton } from '@contentful/f36-button';
import { Text, Subheading } from '@contentful/f36-typography';

import { useModalHeader } from '../useModalHeader';
import { getModalHeaderStyles } from './ModalHeader.styles';

interface ModalHeaderInternalProps extends CommonProps {
  title?: string;
  subtitle?: string;
  /**Used for linking aria-labelledby, fallback is autogenerated */
  titleId?: string;
  /**Used for linking aria-describedby, fallback is autogenerated */
  subtitleId?: string;
  /**
   * @deprecated Pass the header via the Modal `header` slot instead; it takes `onClose` from the Modal.
   */
  onClose?: ReactModal.Props['onRequestClose'];
  children?: React.ReactNode;
  aria?: {
    closeIconLabel?: string;
  };
}

type ModalHeaderBaseProps = PropsWithHTMLElement<
  ModalHeaderInternalProps,
  'div'
>;

export type ModalHeaderProps = ModalHeaderBaseProps & { title: string };

/**
 * Internal: `title` is optional so `Modal` can always render the close button.
 * Not part of the public API, use `ModalHeader`.
 */
export const ModalHeaderBase = ({
  onClose,
  title,
  titleId,
  subtitleId,
  subtitle,
  testId = 'cf-ui-modal-header',
  className,
  children,
  aria,
  ...otherProps
}: ModalHeaderBaseProps): React.ReactElement => {
  const styles = getModalHeaderStyles();
  const {
    titleId: resolvedTitleId,
    subtitleId: resolvedSubtitleId,
    onClose: resolvedOnClose,
    closeIconLabel,
  } = useModalHeader({
    title,
    subtitle,
    titleId,
    subtitleId,
    onClose,
    closeIconLabel: aria?.closeIconLabel,
  });

  const noVisibleTitle = !title && !subtitle;

  return (
    <Flex
      {...otherProps}
      className={cx(styles.root, className, {
        [styles.noBorder]: noVisibleTitle,
      })}
      testId={testId}
      alignItems="center"
      justifyContent="space-between"
    >
      {!noVisibleTitle && (
        <Text as="hgroup" isTruncated>
          {title && (
            <Subheading
              id={resolvedTitleId}
              as="h2"
              marginBottom="none"
              className={styles.title}
            >
              {title}
            </Subheading>
          )}
          {subtitle && (
            <Text
              id={resolvedSubtitleId}
              marginLeft="spacingXs"
              fontColor="gray700"
              as="p"
              className={styles.title}
            >
              {subtitle}
            </Text>
          )}
        </Text>
      )}
      {children}
      {resolvedOnClose && (
        <Flex alignItems="center" className={styles.buttonContainer}>
          <IconButton
            variant="transparent"
            aria-label={closeIconLabel}
            size="small"
            icon={<XIcon size="small" />}
            onClick={resolvedOnClose}
          />
        </Flex>
      )}
    </Flex>
  );
};

ModalHeaderBase.displayName = 'ModalHeaderBase';

export const ModalHeader = (props: ModalHeaderProps): React.ReactElement => (
  <ModalHeaderBase {...props} />
);

ModalHeader.displayName = 'ModalHeader';
